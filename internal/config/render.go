package config

import (
	"fmt"
	"sort"
	"strings"
)

// Rendered is the set of files an effective Spec turns into. Keys are absolute paths below the agent's root.
type Rendered map[string]string

// Paths of the generated drop-ins. k3s reads <config>.d/*.yaml next to the explicit --config file; list keys with a "+"
// suffix append to the base file, so the kubelet flags below come after (and so win over) the image defaults.
const (
	K3sDropin    = "/var/lib/edge/k3s-config.yaml.d/50-edge-node-config.yaml"
	SysctlDropin = "/run/sysctl.d/99-edge-node-config.conf"
	TimesyncConf = "/run/systemd/timesyncd.conf.d/60-edge-node-config.conf"
	LockdownFlag = "/var/lib/edge/config/module-lockdown"
)

func kv(m map[string]string, sep string) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, k+sep+m[k])
	}
	return strings.Join(parts, ",")
}

// Render produces the drop-in files. It never writes bootstrap settings (server, token, node name, taints, flannel interface).
func Render(s Spec) Rendered {
	r := Rendered{}
	var y []string
	var kargs []string
	if k := s.Kubelet; k != nil {
		if len(k.SystemReserved) > 0 {
			kargs = append(kargs, "system-reserved="+kv(k.SystemReserved, "="))
		}
		if len(k.KubeReserved) > 0 {
			kargs = append(kargs, "kube-reserved="+kv(k.KubeReserved, "="))
		}
		if len(k.EvictionHard) > 0 {
			kargs = append(kargs, "eviction-hard="+kv(k.EvictionHard, "<"))
		}
		if k.MaxPods != nil {
			kargs = append(kargs, fmt.Sprintf("max-pods=%d", *k.MaxPods))
		}
		if k.ImageGCHigh != nil {
			kargs = append(kargs, fmt.Sprintf("image-gc-high-threshold=%d", *k.ImageGCHigh))
		}
		if k.ImageGCLow != nil {
			kargs = append(kargs, fmt.Sprintf("image-gc-low-threshold=%d", *k.ImageGCLow))
		}
	}
	if len(kargs) > 0 {
		y = append(y, "kubelet-arg+:")
		for _, a := range kargs {
			y = append(y, fmt.Sprintf("  - %q", a))
		}
	}
	if len(s.NodeLabels) > 0 {
		keys := make([]string, 0, len(s.NodeLabels))
		for k := range s.NodeLabels {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		y = append(y, "node-label+:")
		for _, k := range keys {
			y = append(y, fmt.Sprintf("  - %q", k+"="+s.NodeLabels[k]))
		}
	}
	if s.DisableNetworkPolicy != nil {
		y = append(y, fmt.Sprintf("disable-network-policy: %t", *s.DisableNetworkPolicy))
	}
	if s.K3sLogLevel != nil {
		y = append(y, fmt.Sprintf("v: %d", *s.K3sLogLevel))
	}
	r[K3sDropin] = strings.Join(append([]string{"# generated by noded from EdgeNodeConfig; do not edit"}, y...), "\n") + "\n"

	var sc []string
	keys := make([]string, 0, len(s.Sysctls))
	for k := range s.Sysctls {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		sc = append(sc, fmt.Sprintf("%s = %s", k, s.Sysctls[k]))
	}
	r[SysctlDropin] = strings.Join(append([]string{"# generated by noded from EdgeNodeConfig"}, sc...), "\n") + "\n"

	if len(s.TimeServers) > 0 {
		r[TimesyncConf] = "[Time]\nNTP=" + strings.Join(s.TimeServers, " ") + "\n"
	} else {
		r[TimesyncConf] = "[Time]\n"
	}
	// moduleLockdown defaults to on (the image's baseline); the flag file exists only when it is explicitly disabled.
	if s.ModuleLockdown != nil && !*s.ModuleLockdown {
		r[LockdownFlag] = "off\n"
	}
	return r
}

// Impact says which services an apply must touch, by comparing two renderings.
type Impact struct {
	RestartK3s, ReloadSysctl, RestartTimesync bool
}

func Diff(old, new Rendered) (changed []string, im Impact) {
	seen := map[string]bool{}
	for p := range old {
		seen[p] = true
	}
	for p := range new {
		seen[p] = true
	}
	for p := range seen {
		if old[p] == new[p] {
			continue
		}
		changed = append(changed, p)
		switch p {
		case K3sDropin:
			im.RestartK3s = true
		case SysctlDropin:
			im.ReloadSysctl = true
		case TimesyncConf:
			im.RestartTimesync = true
		}
	}
	sort.Strings(changed)
	return
}
