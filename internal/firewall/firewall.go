// Package firewall builds and applies the host ingress firewall: an nftables table "inet edge" with a default-drop input
// chain. Rules come from FirewallRule objects with type Host that select this node, plus a built-in baseline. Loopback,
// the Tailscale interface, the pod network and established flows are always accepted, so the tailnet path to noded and the
// kubelet cannot be cut off by a bad rule.
package firewall

import (
	"context"
	"fmt"
	"net/netip"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

type Port struct {
	Port     int    `json:"port"`
	Protocol string `json:"protocol"`
}

// Rule mirrors the FirewallRule spec fields the host firewall uses.
type Rule struct {
	Name         string
	Type         string            `json:"type"`
	NodeName     string            `json:"nodeName"`
	NodeSelector map[string]string `json:"nodeSelector"`
	Ports        []Port            `json:"ports"`
	Sources      []string          `json:"sources"`
}

// Baseline is what a node with no FirewallRule objects allows from anywhere.
var Baseline = []Port{{53, "UDP"}, {53, "TCP"}, {80, "TCP"}, {443, "TCP"}, {41641, "UDP"}}

// extraFromEnv reads EDGE_FIREWALL_EXTRA_PORTS ("7777/tcp,8080/udp"): additional baseline ports for environments where noded is
// not reached over Tailscale (the KVM tests). Unset in production; invalid entries are ignored.
func extraFromEnv() []Port {
	var out []Port
	for _, f := range strings.Split(os.Getenv("EDGE_FIREWALL_EXTRA_PORTS"), ",") {
		n, proto, ok := strings.Cut(strings.TrimSpace(f), "/")
		p, err := strconv.Atoi(n)
		if !ok || err != nil || p < 1 || p > 65535 {
			continue
		}
		if proto = strings.ToUpper(proto); proto == "TCP" || proto == "UDP" {
			out = append(out, Port{p, proto})
		}
	}
	return out
}

// TrustedIfaces are accepted whatever the rules say.
var TrustedIfaces = []string{"lo", "tailscale0", "cni0", "flannel.1", "flannel-wg", "kube-bridge"}

// PodCIDRs are the k3s defaults (pods and services); traffic from them is accepted.
var PodCIDRs = []string{"10.42.0.0/16", "10.43.0.0/16"}

func (r Rule) selects(node string, labels map[string]string) bool {
	if r.Type != "Host" {
		return false
	}
	if r.NodeName != "" && r.NodeName != node {
		return false
	}
	for k, v := range r.NodeSelector {
		if labels[k] != v {
			return false
		}
	}
	return true
}

// Validate checks the pieces that end up in nft syntax; nothing user supplied reaches the ruleset unchecked.
func (r Rule) Validate() error {
	if len(r.Ports) == 0 {
		return fmt.Errorf("rule %s: no ports", r.Name)
	}
	for _, p := range r.Ports {
		if p.Port < 1 || p.Port > 65535 {
			return fmt.Errorf("rule %s: port %d out of range", r.Name, p.Port)
		}
		if pr := strings.ToUpper(p.Protocol); pr != "" && pr != "TCP" && pr != "UDP" {
			return fmt.Errorf("rule %s: protocol %q", r.Name, p.Protocol)
		}
	}
	for _, s := range r.Sources {
		if _, err := netip.ParsePrefix(s); err != nil {
			return fmt.Errorf("rule %s: source %q is not a CIDR", r.Name, s)
		}
	}
	return nil
}

type key struct {
	proto string
	port  int
	src   string // "" = anywhere
}

// Build returns the nft script for this node. Invalid rules are skipped and reported in the second result; the rest apply.
func Build(rules []Rule, node string, labels map[string]string) (string, []error) {
	var errs []error
	allowed := map[key]bool{}
	add := func(p Port, src string) {
		pr := strings.ToLower(p.Protocol)
		if pr == "" {
			pr = "tcp"
		}
		allowed[key{pr, p.Port, src}] = true
	}
	for _, p := range append(append([]Port{}, Baseline...), extraFromEnv()...) {
		add(p, "")
	}
	for _, r := range rules {
		if !r.selects(node, labels) {
			continue
		}
		if err := r.Validate(); err != nil {
			errs = append(errs, err)
			continue
		}
		srcs := r.Sources
		if len(srcs) == 0 {
			srcs = []string{""}
		}
		for _, p := range r.Ports {
			for _, s := range srcs {
				if s == "0.0.0.0/0" || s == "::/0" {
					s = ""
				}
				add(p, s)
			}
		}
	}
	keys := make([]key, 0, len(allowed))
	for k := range allowed {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		a, b := keys[i], keys[j]
		if a.proto != b.proto {
			return a.proto < b.proto
		}
		if a.port != b.port {
			return a.port < b.port
		}
		return a.src < b.src
	})
	var b strings.Builder
	b.WriteString("# generated by noded; do not edit\ntable inet edge\ndelete table inet edge\ntable inet edge {\n chain input {\n  type filter hook input priority 0; policy drop;\n")
	b.WriteString("  ct state established,related accept\n  ct state invalid drop\n")
	fmt.Fprintf(&b, "  iifname { %s } accept\n", quoteList(TrustedIfaces))
	for _, c := range PodCIDRs {
		fmt.Fprintf(&b, "  ip saddr %s accept\n", c)
	}
	b.WriteString("  ip protocol icmp accept\n  meta l4proto ipv6-icmp accept\n  udp sport 67 udp dport 68 accept\n  udp sport 547 udp dport 546 accept\n")
	for _, k := range keys {
		src := ""
		if k.src != "" {
			if p, _ := netip.ParsePrefix(k.src); p.Addr().Is4() {
				src = "ip saddr " + k.src + " "
			} else {
				src = "ip6 saddr " + k.src + " "
			}
		}
		fmt.Fprintf(&b, "  %s%s dport %d accept\n", src, k.proto, k.port)
	}
	b.WriteString(" }\n}\n")
	return b.String(), errs
}

func quoteList(l []string) string {
	q := make([]string, len(l))
	for i, s := range l {
		q[i] = `"` + s + `"`
	}
	return strings.Join(q, ", ")
}

// ---- applying ----------------------------------------------------------------------------------------------------------

// Host performs the side effects (tests use a fake).
type Host interface {
	Load(ctx context.Context, script string) error // nft -f
	Verify(ctx context.Context) error              // can the node still reach what it needs (the API server)?
	ReadLKG() string
	WriteLKG(script string) error
}

// verifyWait is the pause between verification attempts (a variable so tests can shorten it).
var verifyWait = 5 * time.Second

type Result struct {
	State string // applied | unchanged | rolled-back | rejected
	Error string
}

// Apply loads script atomically. If verification fails afterwards (the revert timer of `try` mode) the previous ruleset
// is loaded again. A script that nft refuses leaves the running rules untouched (nft -f is atomic).
func Apply(ctx context.Context, h Host, script string) Result {
	prev := h.ReadLKG()
	if script == prev {
		return Result{State: "unchanged"}
	}
	if err := h.Load(ctx, script); err != nil {
		return Result{State: "rejected", Error: err.Error()}
	}
	var verr error
	for i := 0; i < 4; i++ {
		if verr = h.Verify(ctx); verr == nil {
			break
		}
		select {
		case <-ctx.Done():
			return Result{State: "rolled-back", Error: ctx.Err().Error()}
		case <-time.After(verifyWait):
		}
	}
	if verr != nil {
		if prev != "" {
			_ = h.Load(ctx, prev)
		}
		return Result{State: "rolled-back", Error: "verification failed: " + verr.Error()}
	}
	if err := h.WriteLKG(script); err != nil {
		return Result{State: "applied", Error: "ruleset is active but could not be saved: " + err.Error()}
	}
	return Result{State: "applied"}
}
